from typing import List, Optional, Dict, Any
from pydantic import BaseModel, Field


class ModelMetrics(BaseModel):
    accuracy: float
    precision: float
    recall: float
    f1_score: float
    confusion_matrix: List[List[int]]
    classification_report: Dict[str, Any]
    feature_importances: Dict[str, float]
    train_samples: int
    test_samples: int


class ModelStatusResponse(BaseModel):
    is_trained: bool
    model_version: Optional[str] = None
    trained_at: Optional[str] = None
    samples_count: Optional[int] = None
    features: List[str] = []
    at_risk_threshold: float
    metrics: Optional[ModelMetrics] = None
    note: str


class ModelTrainRequest(BaseModel):
    force_retrain: bool = False
    test_size: float = Field(default=0.2, ge=0.1, le=0.5)
    random_state: int = 42
    at_risk_threshold: Optional[float] = None


class ModelTrainResponse(BaseModel):
    success: bool
    message: str
    model_version: Optional[str] = None
    dataset_size: int
    metrics: Optional[ModelMetrics] = None
    features_used: List[str] = []


class StudentPredictRequest(BaseModel):
    student_id: Optional[str] = None
    roll_number: Optional[str] = None
    # Optional manual feature vector override for what-if simulation:
    features: Optional[Dict[str, float]] = None


class PredictionResponse(BaseModel):
    student_id: Optional[str] = None
    roll_number: Optional[str] = None
    predicted_risk: str  # "High Risk", "Moderate Risk", "Low Risk"
    risk_probability: float  # calibrated probability between 0 and 1
    confidence_score: float
    is_model_prediction: bool  # True if from trained XGBoost, False if heuristic fallback
    contributing_factors: List[str]
    model_version: str
    prediction_timestamp: str
    features_evaluated: Dict[str, Any]
    disclaimer: str = (
        "Predictions are decision-support estimates generated by machine learning. "
        "They should not be treated as guaranteed future academic outcomes."
    )
